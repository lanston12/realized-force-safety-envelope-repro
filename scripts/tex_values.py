"""Generate TeX result values exclusively from regenerated CSV/JSON."""
from pathlib import Path
import csv,json
R=Path(__file__).resolve().parents[1]
def read(p):
    with (R/p).open(encoding='utf8') as f:return list(csv.DictReader(f))
sel=read('tables_v5/selected_analytical_results.csv');mix=read('tables_v5/interface_comparison.csv')
out={};trace={}
def value(name,x,source,digits=3):
    out[name]=f'{float(x):.{digits}f}';trace[name]={'value':float(x),'source':source}
for r in sel:
    code={'ideal_identity':'Ideal','common_force':'Common','realized':'Real'}[r['interface']]+{'15':'Fifteen','16':'Sixteen','18':'Eighteen'}[r['v']]+{'0':'Level','-0.03':'DownThree','-0.06':'DownSix'}[r['grade']]
    value(code+'Gap',r['fresh_gap'],'tables_v5/selected_analytical_results.csv')
    if r['Tmax']:value(code+'Age',r['Tmax'],'tables_v5/selected_analytical_results.csv')
for r in mix:
    code={'ideal_identity':'Ideal','common_force':'Common','realized':'Real'}[r['interface']]
    value(code+'Head',r['hmin'],'tables_v5/interface_comparison.csv');value(code+'MixGap',r['dsafe'],'tables_v5/interface_comparison.csv')
value('HeadIncrease',float(mix[2]['hmin'])-float(mix[0]['hmin']),'tables_v5/interface_comparison.csv')
s=json.loads((R/'results_processed_v5/analytical_summary.json').read_text())
value('SectorEta',s['eta_09'],'results_processed_v5/analytical_summary.json',10)
value('MinSectorSlack',s['min_directional_margin_N'],'results_processed_v5/analytical_summary.json',6)
for name,key in [('ForceChecks','n_directional_checks'),('AgeRows','fig3_rows'),('HeadRows','fig4_rows')]:value(name,s[key],'results_processed_v5/analytical_summary.json',0)
(R/'sections/results_values.tex').write_text('% Generated by scripts/tex_values.py; do not edit.\n'+'\n'.join('\\newcommand{\\'+k+'}{'+v+'}' for k,v in out.items())+'\n',encoding='utf8')
(R/'audit/tex_value_provenance.json').write_text(json.dumps(trace,indent=2),encoding='utf8')
lines=[r'\begin{tabular}{rrrr}',r'\toprule',r'$v$ (m/s)&Grade&Fresh $d_{\rm safe}$ (m)&$T_{\max}$ (s)\\\midrule']
for v,g in [(15,0),(15,-.03),(15,-.06),(16,0),(16,-.03),(18,0)]:
    r=next(r for r in sel if float(r['v'])==v and float(r['grade'])==g and r['interface']=='realized')
    age='Inadmissible' if not r['Tmax'] else f"{float(r['Tmax']):.3f}"+(' (cap)' if r['admission']=='age_cap' else '')
    lines.append(f"{v}&${g*100:g}$\\%&{float(r['fresh_gap']):.3f}&{age}"+r'\\')
lines += [r'\bottomrule',r'\end{tabular}']
(R/'tables_v5/table_age.tex').write_text('\n'.join(lines),encoding='utf8')
